// Inline require_relative into a single Ruby file.
//
// The browser Ruby VM resolves require_relative over HTTP, one request per
// source file. The gemstone example pulls in 83 files, so an unbundled deploy
// pays 83 sequential round trips on every page load. Bundling turns that into
// one request.
//
// Only literal top-level `require_relative "path"` lines are inlined, matching
// what JS::RequireRemote itself resolves. `require "stdlib"` lines are kept.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const [entry, output] = process.argv.slice(2);

if (!entry || !output) {
  throw new Error("usage: node scripts/bundle-ruby.mjs <entry.rb> <output.rb>");
}

const root = process.cwd();
const requireRelative = /^require_relative\s+"([^"]+)"\s*$/;
const frozenStringLiteral = /^#\s*frozen_string_literal:/;

function inline(file, seen) {
  if (seen.has(file)) return null;
  seen.add(file);

  let source;
  try {
    source = readFileSync(file, "utf8");
  } catch (error) {
    throw new Error(`cannot resolve require_relative target: ${relative(root, file)}`, { cause: error });
  }

  const lines = [`# ---- ${relative(root, file)}`];
  for (const line of source.split("\n")) {
    const match = requireRelative.exec(line);
    if (match) {
      const nested = inline(resolve(dirname(file), `${match[1]}.rb`), seen);
      if (nested !== null) lines.push(nested);
      continue;
    }
    if (frozenStringLiteral.test(line)) continue;

    lines.push(line);
  }

  return lines.join("\n");
}

const entryPath = resolve(root, entry);
const outputPath = resolve(root, output);
const seen = new Set();
const body = inline(entryPath, seen);

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `# frozen_string_literal: true
# Generated by scripts/bundle-ruby.mjs from ${relative(root, entryPath)}. Do not edit.

${body}
`
);

process.stdout.write(`bundled ${seen.size} Ruby files into ${relative(root, outputPath)}\n`);
